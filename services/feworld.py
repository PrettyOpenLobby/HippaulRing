#!/usr/bin/env python3
"""feworld.py -- Fantasy Earth's WORLD door, the port MSG_LOBBY_JOIN_GAME_OK
hands the client to (54850 in our deployment).

Reached for the first time 2026-08-17, immediately after the lobby closed: a
player created a character, selected it, picked the world, and the client dialled
here. Its own log for that moment:

    >MSG_LOBBY_JOIN_GAME_OK : IP(127.0.0.1):Port(54850) CODE=1
     FE_NETWORK :: Connect / IP=127.0.0.1 port=54850 /mode=2
     Login Seq. :: relay conn( 127.0.0.1 54850 )

TWO THINGS ARE KNOWN ABOUT THIS PORT WITHOUT A SINGLE CAPTURE, both read off the
unpacked FE_Client image, and they are why this file can exist at all:

  1. **It speaks the same transport as the lobby.** The relay connect
     (`0x50483b0`) passes mode **2** to `0x5046b40`, and the cipher exchange at
     `0x05046804` runs whenever that mode is 1..2. The LLB (54848) dials with
     mode 0, which is exactly why 54848 is plaintext and both 54849 and this port
     are not. So `fenet`'s handshake applies unchanged -- master key
     `fantasyearth`, FE's +1 tables, little-endian halves.
  2. **The first message is `0x20 MSG_AUTH_CODE_NOTIFY`**, carrying the CODE
     dword the lobby handed out in `0x7821`. Built at `0x5046c80`:
     `beginMessage(0x20)` + `writeDword(code)` + flush, logged by the client as
     `<MSG_AUTH_CODE_NOTIFY : CODE = %d`.

WHAT THIS DOES, AND DELIBERATELY DOES NOT DO. It completes the key exchange and
then READS. Nothing about the world protocol past `0x20` is measured yet, so it
answers nothing and guesses nothing -- it decodes each frame with the machinery
we already trust and prints it. The first session through here is a CAPTURE whose
job is to tell us what the client asks for next.

WARNING: IT STILL HANGS UP ON AN IDLE CONNECTION (`--read-window`), and that is not
optional. The warning that governs every FE port applies here too: a bind that
accepts and then leaves the client waiting is worse than no bind, because the
player cannot get back to the Viewer. Closing lets FE fail fast and say so. Do
not "improve" this by holding the socket open to see more.

    python services/feworld.py --port 54850 --captures 0 --life 0
"""
